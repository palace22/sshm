"""Open several connections as tabs, using a private tmux server as the engine.

sshm talks to its own server (``tmux -L sshm``) with a generated config, so
the user's tmux setup, sessions and key bindings are never touched. When sshm
already runs inside tmux, hosts open as new windows of the current session.
"""

import os
import re
import shlex
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

SOCKET = "sshm"
SESSION = "sshm"
MIN_TMUX = (3, 0)
TABS_ENV = "SSHM_TABS"  # set in every tab, so sshm knows it runs inside one
PASSTHROUGH_ENV = ("SSHM_CONFIG", "SSHM_NO_ANIM")

ACCENT = "colour45"  # cyan, like the picker

_CONF = """\
# Generated by sshm every time tabs are opened; edits are overwritten.
set -g mouse on
set -g base-index 1
setw -g pane-base-index 1
set -g renumber-windows on
set -s escape-time 10
set -g history-limit 50000
set -g set-titles on
set -g set-titles-string "sshm: #W"
setw -g allow-rename off
setw -g automatic-rename off
setw -g monitor-activity on
set -g visual-activity off
set -g remain-on-exit failed
set -g remain-on-exit-format \
"#[reverse] exit #{{pane_dead_status}} #[noreverse] connection closed   \
alt-r reconnect   alt-w close"

set -g status-position top
set -g status-style "bg=colour235,fg=colour250"
set -g message-style "bg={accent},fg=colour16"
set -g status-left "#[bg={accent},fg=colour16,bold] sshm #[default] "
set -g status-left-length 12
set -g window-status-separator ""
setw -g window-status-format "#[fg=colour245] #I #W "
setw -g window-status-current-format "#[bg=colour252,fg=colour16,bold] #I #W "
setw -g window-status-activity-style "fg=colour214"
set -g status-right-length 90
set -g status-right "#[range=user|new]#[fg={accent},bold][ + ]#[norange]\
#[fg=colour242]  alt-</> switch  alt-n new  alt-w close  alt-d detach "
{environment}
bind -n M-Left previous-window
bind -n M-Right next-window
bind -n S-Left previous-window
bind -n S-Right next-window
{numbers}
bind -n M-n new-window -n new {picker}
bind -n M-w confirm-before -p "close #W? (y/n)" kill-window
bind -n M-r respawn-pane -k
bind -n M-d detach-client
bind -n MouseDown1Status if -F "#{{==:#{{mouse_status_range}},new}}" \
{{ new-window -n new {picker} }} {{ select-window -t = }}
"""


@dataclass
class Tab:
    name: str
    command: List[str]


def tmux_version() -> Optional[Tuple[int, int]]:
    if shutil.which("tmux") is None:
        return None
    out = subprocess.run(["tmux", "-V"], capture_output=True, text=True).stdout
    match = re.search(r"(\d+)\.(\d+)", out)
    return (int(match.group(1)), int(match.group(2))) if match else None


def in_tmux() -> bool:
    return bool(os.environ.get("TMUX"))


def in_tab() -> bool:
    """True when running inside a tab opened by sshm."""
    return in_tmux() and os.environ.get(TABS_ENV) == "1"


def rename_current(name: str) -> None:
    subprocess.run(["tmux", "rename-window", name], check=False)


class TabSession:
    """The sshm tab session on the private tmux server."""

    def __init__(self, conf_path: Path, socket: str = SOCKET):
        self.conf_path = conf_path
        self.socket = socket

    def _tmux(
        self, *args: str, check: bool = True
    ) -> "subprocess.CompletedProcess[str]":
        # Inside tmux, talk to the current server (TMUX is honoured without -L).
        prefix = ["tmux"] if in_tmux() else ["tmux", "-L", self.socket]
        return subprocess.run(
            [*prefix, *args], check=check, capture_output=True, text=True
        )

    @staticmethod
    def _environment() -> Dict[str, str]:
        """Variables every tab needs: the tab marker plus sshm's own settings."""
        passthrough = {k: os.environ[k] for k in PASSTHROUGH_ENV if k in os.environ}
        return {TABS_ENV: "1", **passthrough}

    def _env(self) -> List[str]:
        return [f for k, v in self._environment().items() for f in ("-e", f"{k}={v}")]

    def check(self) -> None:
        version = tmux_version()
        if version is None:
            raise ValueError(
                "Tabs need tmux. Install it (e.g. 'sudo dnf install tmux' or "
                "'sudo apt install tmux') and try again."
            )
        if version < MIN_TMUX:
            raise ValueError(f"Tabs need tmux {MIN_TMUX[0]}.{MIN_TMUX[1]} or newer")

    def exists(self) -> bool:
        if in_tmux():
            return False
        return self._tmux("has-session", "-t", SESSION, check=False).returncode == 0

    def write_conf(self) -> Path:
        picker = shlex.join([sys.executable, "-m", "sshm"])
        environment = "\n".join(
            f'set-environment -g {k} "{v}"' for k, v in self._environment().items()
        )
        numbers = "\n".join(
            f"bind -n M-{i} select-window -t :={i}" for i in range(1, 10)
        )
        text = _CONF.format(
            accent=ACCENT,
            picker=f'"{picker}"',
            environment=environment,
            numbers=numbers,
        )
        self.conf_path.parent.mkdir(parents=True, exist_ok=True)
        self.conf_path.write_text(text, encoding="utf-8")
        return self.conf_path

    def open(self, tabs: Sequence[Tab]) -> bool:
        """Open one window per tab. Returns True when the caller should attach
        (False when already inside tmux: the windows are simply added)."""
        self.check()
        if not tabs:
            return False
        if in_tmux():
            for tab in tabs:
                self._tmux(
                    "new-window", "-n", tab.name, *self._env(), shlex.join(tab.command)
                )
            return False

        conf = str(self.write_conf())
        first_id = None
        pending = list(tabs)
        if not self.exists():
            tab = pending.pop(0)
            first_id = self._tmux(
                "-f",
                conf,
                "new-session",
                "-d",
                "-s",
                SESSION,
                "-n",
                tab.name,
                "-P",
                "-F",
                "#{window_id}",
                *self._env(),
                shlex.join(tab.command),
            ).stdout.strip()
        self._tmux("source-file", conf, check=False)
        for tab in pending:
            window_id = self._tmux(
                "new-window",
                "-t",
                f"{SESSION}:",
                "-n",
                tab.name,
                "-P",
                "-F",
                "#{window_id}",
                *self._env(),
                shlex.join(tab.command),
            ).stdout.strip()
            first_id = first_id or window_id
        if first_id:
            self._tmux("select-window", "-t", first_id)
        return True

    def windows(self) -> List[str]:
        if not self.exists():
            return []
        out = self._tmux("list-windows", "-t", SESSION, "-F", "#W").stdout
        return out.split()

    def attach(self) -> None:
        """Replace this process with a tmux client attached to the session."""
        os.execvp("tmux", ["tmux", "-L", self.socket, "attach-session", "-t", SESSION])

    def close(self) -> None:
        self._tmux("kill-session", "-t", SESSION, check=False)
